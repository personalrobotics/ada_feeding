"""
This script loads and analyzes one or more comprehensive JSON results files
generated by `constrained_task_space_benchmark.py`. It generates a series of
side-by-side comparative plots to evaluate different planning methodologies.

Requires: pandas, plotly
Install with: pip install pandas plotly
"""

import argparse
import json
import os
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go


def load_data(json_files: list[str]) -> pd.DataFrame:
    """Loads and concatenates results from multiple JSON files."""
    all_data = []
    for file_path in json_files:
        print(f"Loading data from {file_path}...")
        try:
            with open(file_path, "r") as f:
                data = json.load(f)
                all_data.extend(data)
        except (FileNotFoundError, json.JSONDecodeError) as e:
            print(
                f"  - Warning: Could not load or parse {file_path}. Skipping. Error: {e}"
            )
            continue

    if not all_data:
        print("Error: No valid data loaded.")
        return pd.DataFrame()

    df = pd.json_normalize(all_data, sep="_")
    print(
        f"Successfully loaded a total of {len(df)} trials from {len(json_files)} file(s)."
    )
    return df


def plot_success_rates(df: pd.DataFrame, output_dir: str):
    """Plots planner and verification success rates grouped by planning mode."""
    print("Generating success rate plot...")
    summary = (
        df.groupby("planning_mode")
        .agg(
            planner_success=("plan_success", "mean"),
            verification_success=("verification_success", "mean"),
        )
        .reset_index()
    )
    summary["planner_success"] *= 100
    summary["verification_success"] *= 100

    summary_long = summary.melt(
        id_vars="planning_mode",
        value_vars=["planner_success", "verification_success"],
        var_name="Metric",
        value_name="Success Rate (%)",
    )

    fig = px.bar(
        summary_long,
        x="planning_mode",
        y="Success Rate (%)",
        color="Metric",
        title="Planner vs. Verification Success Rates by Methodology",
        labels={"planning_mode": "Planning Methodology"},
        barmode="group",
        text_auto=".1f",
        category_orders={
            "planning_mode": [
                "joint_unconstrained",
                "task_pos_unconstrained",
                "task_pos_constrained",
                "task_pos_yaw_constrained",
            ]
        },
    )
    fig.update_layout(yaxis_range=[0, 105], legend_title_text="Success Metric")

    filename = os.path.join(output_dir, "comparative_success_rates.html")
    fig.write_html(filename)
    print(f"  - Saved to {filename}")


def plot_comparative_metric(
    df: pd.DataFrame,
    metric_col: str,
    title: str,
    yaxis_title: str,
    filename: str,
    output_dir: str,
):
    """Generic function to create a comparative box plot for a given metric."""
    print(f"Generating plot for: {title}...")
    successful_plans = df[df["plan_success"] == True].copy()
    if successful_plans.empty or metric_col not in successful_plans.columns:
        print(f"  - No data for metric '{metric_col}'. Skipping plot.")
        return

    fig = px.box(
        successful_plans,
        x="planning_mode",
        y=metric_col,
        color="planning_mode",
        title=title,
        labels={"planning_mode": "Planning Methodology", metric_col: yaxis_title},
        category_orders={
            "planning_mode": [
                "joint_unconstrained",
                "task_pos_unconstrained",
                "task_pos_constrained",
                "task_pos_yaw_constrained",
            ]
        },
    )

    filepath = os.path.join(output_dir, filename)
    fig.write_html(filepath)
    print(f"  - Saved to {filepath}")


def plot_articutool_velocities_comparison(df: pd.DataFrame, output_dir: str):
    """Plots a 2D histogram of required Articutool velocities, faceted by mode."""
    print("Generating Articutool velocity comparison plot...")
    successful_plans = df[df["plan_success"] == True].copy()

    velocity_data = []
    for index, row in successful_plans.iterrows():
        waypoints = row.get("trajectory_metrics_waypoints_data")
        if waypoints and isinstance(waypoints, list):
            for wp in waypoints:
                vels = wp.get("articutool_velocities_rad_per_sec")
                if vels and isinstance(vels, dict):
                    velocity_data.append(
                        {
                            "planning_mode": row["planning_mode"],
                            "pitch_vel": vels.get("pitch_vel"),
                            "roll_vel": vels.get("roll_vel"),
                        }
                    )

    if not velocity_data:
        print("  - No velocity data found to plot.")
        return

    vel_df = pd.DataFrame(velocity_data).dropna()

    fig = px.density_heatmap(
        vel_df,
        x="pitch_vel",
        y="roll_vel",
        facet_col="planning_mode",
        facet_col_wrap=2,
        title="Distribution of Required Articutool Velocities by Methodology",
        labels={
            "pitch_vel": "Pitch Velocity (rad/s)",
            "roll_vel": "Roll Velocity (rad/s)",
        },
        category_orders={
            "planning_mode": [
                "joint_unconstrained",
                "task_pos_unconstrained",
                "task_pos_constrained",
                "task_pos_yaw_constrained",
            ]
        },
    )

    filename = os.path.join(output_dir, "comparative_articutool_velocities.html")
    fig.write_html(filename)
    print(f"  - Saved to {filename}")


def plot_3d_trajectories(df: pd.DataFrame, output_dir: str, num_examples: int = 5):
    """Plots start/end points and example trajectories in 3D space."""
    if df.empty or "trajectory_metrics_waypoints_data" not in df.columns:
        return

    print("Generating 3D trajectory plot...")
    successful_plans = df[df["plan_success"] == True].copy()
    if successful_plans.empty:
        print("  - No successful plans to plot.")
        return

    end_points, start_points = [], []
    for _, row in successful_plans.iterrows():
        waypoints = row["trajectory_metrics_waypoints_data"]
        if waypoints and isinstance(waypoints, list) and len(waypoints) > 0:
            start_points.append(waypoints[0]["ee_pose_world"]["position"])
            end_points.append(waypoints[-1]["ee_pose_world"]["position"])

    fig = go.Figure()

    fig.add_trace(
        go.Scatter3d(
            x=[p[0] for p in start_points],
            y=[p[1] for p in start_points],
            z=[p[2] for p in start_points],
            mode="markers",
            marker=dict(color="blue", size=4, opacity=0.6),
            name="Start EE Position",
        )
    )
    fig.add_trace(
        go.Scatter3d(
            x=[p[0] for p in end_points],
            y=[p[1] for p in end_points],
            z=[p[2] for p in end_points],
            mode="markers",
            marker=dict(color="red", size=4, opacity=0.6),
            name="End EE Position",
        )
    )

    example_indices = np.random.choice(
        successful_plans.index, min(num_examples, len(successful_plans)), replace=False
    )
    for i, index in enumerate(example_indices):
        waypoints = successful_plans.loc[index, "trajectory_metrics_waypoints_data"]
        path_x = [wp["ee_pose_world"]["position"][0] for wp in waypoints]
        path_y = [wp["ee_pose_world"]["position"][1] for wp in waypoints]
        path_z = [wp["ee_pose_world"]["position"][2] for wp in waypoints]
        fig.add_trace(
            go.Scatter3d(
                x=path_x,
                y=path_y,
                z=path_z,
                mode="lines",
                line=dict(width=5),
                name=f"Example Traj {i + 1}",
            )
        )

    fig.update_layout(
        title="3D Visualization of End-Effector Trajectories",
        scene=dict(
            xaxis_title="X (m)",
            yaxis_title="Y (m)",
            zaxis_title="Z (m)",
            aspectmode="data",
        ),
        margin=dict(l=0, r=0, b=0, t=40),
    )

    filename = os.path.join(output_dir, "3d_trajectories.html")
    fig.write_html(filename)
    print(f"  - Saved to {filename}")


def main():
    """Main function to load data and generate all plots."""
    parser = argparse.ArgumentParser(
        description="Holistic analysis of benchmark results."
    )
    parser.add_argument(
        "json_files",
        nargs="+",
        help="Path(s) to the comprehensive benchmark results JSON file(s).",
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        default="holistic_analysis_plots",
        help="Directory to save the generated plots.",
    )
    args = parser.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)
    df = load_data(args.json_files)
    if df.empty:
        return

    # Generate all plots
    plot_success_rates(df, args.output_dir)
    plot_comparative_metric(
        df,
        "planning_time_s",
        "Planning Time Comparison",
        "Planning Time (s)",
        "comparative_planning_times.html",
        args.output_dir,
    )
    plot_comparative_metric(
        df,
        "trajectory_metrics_joint_space_path_length_rad",
        "Joint-Space Path Length Comparison",
        "Path Length (rad)",
        "comparative_path_lengths.html",
        args.output_dir,
    )
    plot_articutool_velocities_comparison(df, args.output_dir)
    plot_3d_trajectories(df, args.output_dir)

    print("\nAnalysis complete. Plots saved in:", args.output_dir)


if __name__ == "__main__":
    main()
