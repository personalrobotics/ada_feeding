def main():
    """Main function to load data and generate all plots."""
    parser = argparse.ArgumentParser(
        description="Analyze benchmark results and generate plots."
    )
    parser.add_argument(
        "json_file",
        type=str,
        help="Path to the comprehensive benchmark results JSON file.",
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        default="benchmark_plots",
        help="Directory to save the generated plot HTML files.",
    )
    args = parser.parse_args()

    # Create output directory if it doesn't exist
    os.makedirs(args.output_dir, exist_ok=True)

    # Load data
    df = load_data(args.json_file)
    if df.empty:
        return

    # Generate plots
    plot_success_rates(df, args.output_dir)
    plot_planning_times(df, args.output_dir)
    plot_3d_trajectories(df, args.output_dir)
    plot_articutool_velocities(df, args.output_dir)

    print("\nAnalysis complete. Plots saved in:", args.output_dir)


if __name__ == "__main__":
    main()
